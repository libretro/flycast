def main():
    if sys.argv[1:] == ['--verdict']:
        print('0x%08x' % VERDICT)
        return 0
    program = PROGRAM
    args = sys.argv[1:]
    if args[:1] == ['--own-tlb']:
        # smc_own_tlb, 16 bytes in: see smc_prog.c
        assert program[16:20] == bytes(4)
        program = program[:16] + struct.pack('<I', 1) + program[20:]
        args = args[1:]
    if len(args) != 1:
        sys.stderr.write(__doc__)
        return 2
