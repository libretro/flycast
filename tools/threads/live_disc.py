def cdda_frame(n):
    """Sample @n of the audio track, left and right. Two sawtooth-like
    sequences that never line up with each other, so that a run of samples
    says where in the track it is from, and a dropped, repeated or
    byte-swapped sector shows."""
    return ((n * 37) % 20001 - 10000, (n * 53 + 7) % 19997 - 9998)


# The sound the program puts in the sound chip's memory for a channel to
# play: this many samples of 16-bit PCM, looping.
CHANNEL_SAMPLES = 256


def channel_sample(k):
    """Sample @k of the channel's loop, as live_prog.c writes it."""
    return (k * 97) % 4001 - 2000


# ...and for a second channel, which plays it through its low-pass filter:
# this many samples, a square wave and then silence, with the filter's
# cutoff and resonance registers set to these.
FILTER_SAMPLES = 4096
FILTER_CUTOFF = 0x1900
FILTER_Q = 8


def filter_sample(k):
    """Sample @k of the filtered channel's loop, as live_prog.c writes it."""
    return 0 if k >= 2048 else -6000 if k & 32 else 6000


# ...and for a third, played an octave down: this many samples.
PITCH_SAMPLES = 4096


def pitch_sample(k):
    """Sample @k of the pitched channel's loop, as live_prog.c writes it."""
    return ((k % PITCH_SAMPLES) * 131) % 1999 - 999


def bcd(v):
    return ((v // 10) << 4) | (v % 10)


def raw_sector(lba, data):
    """One MODE1/2352 sector; the core does not check EDC/ECC."""
    fad = lba + 150
    hdr = bytes((bcd(fad // 4500), bcd((fad // 75) % 60), bcd(fad % 75), 1))
    return SYNC + hdr + data.ljust(2048, b'\0') + bytes(2352 - 16 - 2048)


def both32(v):
    return struct.pack('<I', v) + struct.pack('>I', v)


def dirent(name, lba, size, flags):
    ln = 33 + len(name) + ((len(name) + 1) & 1)
    rec = (bytes((ln, 0)) + both32(lba) + both32(size) + bytes(7)
           + bytes((flags, 0, 0)) + struct.pack('<H', 1) + struct.pack('>H', 1)
           + bytes((len(name),)) + name)
    return rec.ljust(ln, b'\0')


