SYNC = b'\x00' + b'\xff' * 10 + b'\x00'
BASE = 45000            # LBA of the high-density data track
ROOT = BASE + 20        # root directory
FILE = BASE + 21        # 1ST_READ.BIN


# The audio track: 300 sectors of 588 stereo samples.
AUDIO_SECTORS = 300


def cdda_frame(n):
    """Sample @n of the audio track, left and right. Two sawtooth-like
    sequences that never line up with each other, so that a run of samples
    says where in the track it is from, and a dropped, repeated or
    byte-swapped sector shows."""
    return ((n * 37) % 20001 - 10000, (n * 53 + 7) % 19997 - 9998)


# The sound the program puts in the sound chip's memory for a channel to
# play: this many samples of 16-bit PCM, looping.
CHANNEL_SAMPLES = 256


def channel_sample(k):
    """Sample @k of the channel's loop, as live_prog.c writes it."""
    return (k * 97) % 4001 - 2000


# ...and for a second channel, which plays it through its low-pass filter:
# this many samples, a square wave and then silence, with the filter's
# cutoff and resonance registers set to these.
FILTER_SAMPLES = 4096
FILTER_CUTOFF = 0x1900
FILTER_Q = 8


def filter_sample(k):
    """Sample @k of the filtered channel's loop, as live_prog.c writes it."""
    return 0 if k >= 2048 else -6000 if k & 32 else 6000


# ...and for a third, played an octave down: this many samples.
PITCH_SAMPLES = 4096


def pitch_sample(k):
    """Sample @k of the pitched channel's loop, as live_prog.c writes it."""
    return ((k % PITCH_SAMPLES) * 131) % 1999 - 999


def bcd(v):
    return ((v // 10) << 4) | (v % 10)


def raw_sector(lba, data):
    """One MODE1/2352 sector; the core does not check EDC/ECC."""
    fad = lba + 150
    hdr = bytes((bcd(fad // 4500), bcd((fad // 75) % 60), bcd(fad % 75), 1))
    return SYNC + hdr + data.ljust(2048, b'\0') + bytes(2352 - 16 - 2048)


def both32(v):
    return struct.pack('<I', v) + struct.pack('>I', v)


def dirent(name, lba, size, flags):
    ln = 33 + len(name) + ((len(name) + 1) & 1)
    rec = (bytes((ln, 0)) + both32(lba) + both32(size) + bytes(7)
           + bytes((flags, 0, 0)) + struct.pack('<H', 1) + struct.pack('>H', 1)
           + bytes((len(name),)) + name)
    return rec.ljust(ln, b'\0')


def write_elf(out):
    """The program on its own, as the ELF file a Dreamcast program is built
    as: one loadable segment at 0x8C010000, where it also starts, with a
    page of zeroes asked for after it."""
    base, offset = 0x8C010000, 0x100
    header = struct.pack('<4s5B7xHHIIIIIHHHHHH',
                         b'\x7fELF', 1, 1, 1, 0, 0,   # 32-bit, little-endian
                         2, 42, 1,                    # executable, SuperH
                         base, 52, 0, 0,              # entry, program headers
                         52, 32, 1, 40, 0, 0)
    segment = struct.pack('<8I', 1, offset, base, base,
                          len(PROGRAM), len(PROGRAM) + 4096, 5, 4)
    with open(out, 'wb') as f:
        f.write((header + segment).ljust(offset, b'\0') + PROGRAM)


def main():
    if sys.argv[1:] == ['--verdict']:
        print('0x%08x' % LIVE_VERDICT)
        return 0
    if len(sys.argv) == 2 and sys.argv[1].endswith('.elf'):
        write_elf(sys.argv[1])
        return 0
    if len(sys.argv) not in (2, 3) or sys.argv[2:] not in ([], ['--no-region-array']):
        sys.stderr.write(__doc__)
        return 2
    out = sys.argv[1]
    program = PROGRAM_NO_REGION_ARRAY if len(sys.argv) == 3 else PROGRAM
    d = os.path.dirname(out) or '.'

    ip = bytearray(16 * 2048)
    meta = (b'SEGA SEGAKATANA ' + b'SEGA ENTERPRISES' + b'0000 ' + b'GD-ROM'
            + b'1/1  ' + b'JUE     ' + b'E000' + b'F' + b'1' + b'0' + b' '
            + b'T-00000   ' + b'V1.000' + b'20260101' + b'        '
            + b'1ST_READ.BIN    ' + b'FLYCAST TEST    '
            + b'THREADS TEST'.ljust(128))
    ip[0:len(meta)] = meta
    # Bootstrap at 0x300: mov.l @(4,pc),r0; jmp @r0; nop; nop; .long 0x8c010000
    ip[0x300:0x30c] = (bytes((0x01, 0xd0, 0x2b, 0x40, 0x09, 0x00, 0x09, 0x00))
                       + struct.pack('<I', 0x8c010000))

    pvd = bytearray(2048)
    pvd[0] = 1
    pvd[1:6] = b'CD001'
    pvd[6] = 1
    pvd[156:156 + 34] = dirent(b'\0', ROOT, 2048, 2)
    root = (dirent(b'\0', ROOT, 2048, 2) + dirent(b'\x01', ROOT, 2048, 2)
            + dirent(b'1ST_READ.BIN;1', FILE, len(program), 0))

    sectors = {}
    for i in range(16):
        sectors[BASE + i] = bytes(ip[i * 2048:(i + 1) * 2048])
    sectors[BASE + 16] = bytes(pvd)
    sectors[ROOT] = root
    for i in range((len(program) + 2047) // 2048):
        sectors[FILE + i] = program[i * 2048:(i + 1) * 2048]

    with open(os.path.join(d, 'track01.bin'), 'wb') as f:
        for lba in range(300):
            f.write(raw_sector(lba, b''))
    with open(os.path.join(d, 'track02.raw'), 'wb') as f:
        f.write(b''.join(struct.pack('<hh', *cdda_frame(n))
                         for n in range(588 * AUDIO_SECTORS)))
    with open(os.path.join(d, 'track03.bin'), 'wb') as f:
        for lba in range(BASE, BASE + 600):
            f.write(raw_sector(lba, sectors.get(lba, b'')))
    with open(out, 'w') as f:
        f.write('3\n1 0 4 2352 track01.bin 0\n2 450 0 2352 track02.raw 0\n'
                '3 %d 4 2352 track03.bin 0\n' % BASE)
    return 0


if __name__ == '__main__':
    sys.exit(main())
